#!/usr/bin/env python3
"""Generate ApertureOS.colors (KDE colour scheme) from tokens.json.

Usage: tools/build.py            (writes ../ApertureOS.colors)
The colour roles follow the Aperture OS rule set:
  orange = interaction / focus / selection
  blue   = information / links / system state
  green  = success, amber = warning, red = error
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "tokens.json").read_text())
C = T["color"]


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, f):
    """Blend colour a towards b by factor f (0..1)."""
    a, b = rgb(a), rgb(b)
    return "#%02X%02X%02X" % tuple(round(x + (y - x) * f) for x, y in zip(a, b))


def kde(h):
    return "%d,%d,%d" % rgb(h)


def group(bg, alt, fg="text"):
    """Common colour set for one KDE colour group."""
    return {
        "BackgroundNormal": bg,
        "BackgroundAlternate": alt,
        "ForegroundNormal": C[fg],
        "ForegroundInactive": C["textMuted"],
        "ForegroundActive": C["orangeBright"],
        "ForegroundLink": C["blue"],
        "ForegroundVisited": C["blueBright"],
        "ForegroundNegative": C["error"],
        "ForegroundNeutral": C["warning"],
        "ForegroundPositive": C["success"],
        "DecorationFocus": C["orange"],
        "DecorationHover": C["orangeDim"],
    }


groups = {
    "Colors:Window": group(C["surface"], mix(C["surface"], C["surfaceElevated"], 0.6)),
    "Colors:View": group(C["background"], mix(C["background"], C["surface"], 0.55)),
    "Colors:Button": group(C["surfaceElevated"], C["surfaceHover"]),
    "Colors:Tooltip": group(C["surfaceElevated"], C["surface"]),
    "Colors:Header": group(C["background"], C["surface"]),
    "Colors:Header][Inactive": group(C["background"], C["surface"]),
    "Colors:Complementary": group(C["background"], C["surface"]),
    "Colors:Selection": {
        **group(C["orange"], C["orangeDim"], "onAccent"),
        "ForegroundNormal": C["onAccent"],
        "ForegroundInactive": "#3A2410",
        "ForegroundActive": C["onAccent"],
        "ForegroundLink": "#002C40",
        "ForegroundVisited": "#00384F",
        "ForegroundNegative": "#5A0000",
        "ForegroundNeutral": "#4A2E00",
        "ForegroundPositive": "#003A1C",
    },
}

lines = [
    "# Generated by tools/build.py from tokens.json - do not edit by hand.",
    "[General]",
    "ColorScheme=ApertureOS",
    "Name=Aperture OS",
    "shadeSortColumn=true",
    "",
    "[KDE]",
    "contrast=6",
    "",
    "[ColorEffects:Disabled]",
    "Color=%s" % kde(C["surface"]),
    "ColorAmount=0.35",
    "ColorEffect=0",
    "ContrastAmount=0.55",
    "ContrastEffect=1",
    "IntensityAmount=0.1",
    "IntensityEffect=2",
    "",
    "[ColorEffects:Inactive]",
    "ChangeSelectionColor=true",
    "Color=%s" % kde(C["background"]),
    "ColorAmount=0.025",
    "ColorEffect=2",
    "ContrastAmount=0.1",
    "ContrastEffect=2",
    "Enable=false",
    "IntensityAmount=0",
    "IntensityEffect=0",
    "",
]
for name, values in groups.items():
    lines.append("[%s]" % name)
    lines += ["%s=%s" % (k, kde(v)) for k, v in values.items()]
    lines.append("")

# Window manager colours (used by Breeze-like decorations and some apps).
lines += [
    "[WM]",
    "activeBackground=%s" % kde(C["background"]),
    "activeBlend=%s" % kde(C["orange"]),
    "activeForeground=%s" % kde(C["text"]),
    "inactiveBackground=%s" % kde(C["background"]),
    "inactiveBlend=%s" % kde(C["border"]),
    "inactiveForeground=%s" % kde(C["textMuted"]),
    "",
]

(ROOT / "ApertureOS.colors").write_text("\n".join(lines))
print("wrote", ROOT / "ApertureOS.colors")
