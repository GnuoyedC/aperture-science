#!/usr/bin/env python3
"""Generate ApertureTokens.qml (design tokens as a QML object) from tokens.json.

Usage: tools/build.py
Writes aperture-os.shell/contents/lockscreen/ApertureTokens.qml
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "aperture-os.shell/contents/lockscreen/ApertureTokens.qml"


def qml_tokens(t):
    lines = ["// Generated by tools/build.py from tokens.json - do not edit by hand.",
             "import QtQuick", "", "QtObject {"]
    for k, v in t["color"].items():
        lines.append('    readonly property color %s: "%s"' % (k, v))
    for k, v in t["alpha"].items():
        lines.append("    readonly property real alpha%s: %s" % (k[0].upper() + k[1:], v))
    for k, v in t["geometry"].items():
        lines.append("    readonly property int %s: %s" % (k, v))
    f = t["font"]
    lines.append('    readonly property string fontUi: "%s"' % f["ui"])
    lines.append('    readonly property string fontUiFallback: "%s"' % f["uiFallback"])
    lines.append('    readonly property string fontDisplay: "%s"' % f.get("display", f["ui"]))
    lines.append('    readonly property string fontDisplayFallback: "%s"' % f.get("displayFallback", f["ui"]))
    lines.append('    readonly property string fontMono: "%s"' % f["mono"])
    lines.append('    readonly property string fontMonoFallback: "%s"' % f["monoFallback"])
    lines.append("    // Resolved families: preferred font if installed, otherwise the fallback.")
    lines.append("    readonly property string ui: Qt.fontFamilies().indexOf(fontUi) >= 0 ? fontUi : fontUiFallback")
    lines.append("    readonly property string mono: Qt.fontFamilies().indexOf(fontMono) >= 0 ? fontMono : fontMonoFallback")
    lines.append("    readonly property string display: Qt.fontFamilies().indexOf(fontDisplay) >= 0 ? fontDisplay"
                 " : (Qt.fontFamilies().indexOf(fontDisplayFallback) >= 0 ? fontDisplayFallback : ui)")
    m = t["motion"]
    for k in ("fast", "normal", "slow", "pulse"):
        lines.append("    readonly property int %s: %s" % (k, m[k]))
    lines.append("    readonly property bool reduceMotion: %s" % str(m["reduceMotion"]).lower())
    lines += ["", "    function alpha(c, a) { return Qt.rgba(c.r, c.g, c.b, a) }", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    tokens = json.loads((ROOT / "tokens.json").read_text())
    TARGET.write_text(qml_tokens(tokens))
    print("wrote", TARGET)
