#!/usr/bin/env python3
"""Build the Aperture OS Aurorae window decoration from tokens.json.

Output: ../aperture-os/ (decoration.svg, button SVGs, aperture-osrc, metadata.desktop)

Look: dark title bar, 1px frame, small radius.
  active   -> frame in subtle Aperture orange + short orange accent on the top edge
  inactive -> muted blue-grey frame
A thin soft shadow lives in the padding area (no thick shadows, no glow).
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "aperture-os"
T = json.loads((ROOT / "tokens.json").read_text())
C, G = T["color"], T["geometry"]

PAD = 8          # shadow padding around the window
B = 1            # visible border
R = G["radiusWindow"]
N = PAD + B      # 9-slice border thickness
CS = 16          # centre / edge length in the sheet
TITLE_ALPHA = 0.97
SHADOW = 0.32


class Sheet:
    def __init__(self):
        self.defs, self.items, self.y, self.w, self.n = [], [], 0, 0, 0

    def grad(self, kind, attrs, stops):
        self.n += 1
        gid = "a%d" % self.n
        s = "".join('<stop offset="%.4f" stop-color="%s" stop-opacity="%.3f"/>' % st for st in stops)
        a = " ".join('%s="%.2f"' % kv for kv in attrs.items())
        self.defs.append('<%sGradient id="%s" gradientUnits="userSpaceOnUse" %s>%s</%sGradient>'
                         % (kind, gid, a, s, kind))
        return "url(#%s)" % gid

    def add(self, eid, body):
        self.items.append('<g id="%s">%s</g>' % (eid, body))

    def svg(self):
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- Generated by aurorae/tools/build.py from tokens.json - do not edit by hand. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">\n<defs>%s</defs>\n%s\n</svg>\n'
                % (self.w, self.y, self.w, self.y, "".join(self.defs), "\n".join(self.items)))


def rect(x, y, w, h, fill, op=1.0, extra=""):
    return '<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" fill="%s" fill-opacity="%.3f" %s/>' % (
        x, y, w, h, fill, op, extra)


SH_STOPS = [(0, "#000000", SHADOW), (0.4, "#000000", SHADOW * 0.4), (0.75, "#000000", SHADOW * 0.1),
            (1, "#000000", 0)]


def decoration(sh, prefix, border_col, border_op, accent, maximized=False):
    """One complete 9-slice decoration set."""
    y0 = sh.y
    n = 0 if maximized else N
    pad = 0 if maximized else PAD
    tot = n + CS + n
    sh.y += tot + 8
    sh.w = max(sh.w, tot + 8)
    x0 = 0
    cells = {
        "topleft": (x0, y0, n, n), "top": (x0 + n, y0, CS, n), "topright": (x0 + n + CS, y0, n, n),
        "left": (x0, y0 + n, n, CS), "center": (x0 + n, y0 + n, CS, CS), "right": (x0 + n + CS, y0 + n, n, CS),
        "bottomleft": (x0, y0 + n + CS, n, n), "bottom": (x0 + n, y0 + n + CS, CS, n),
        "bottomright": (x0 + n + CS, y0 + n + CS, n, n),
    }
    title = C["background"]
    for name, (x, y, w, h) in cells.items():
        parts = []
        if maximized:
            parts.append(rect(x, y, w, h, title, TITLE_ALPHA if name == "center" else 0))
            sh.add(prefix + name, "".join(parts))
            continue
        # --- shadow in the padding area -------------------------------------------
        if name in ("topleft", "topright", "bottomleft", "bottomright"):
            cx = x + (n if name.endswith("left") else 0)
            cy = y + (n if name.startswith("top") else 0)
            # corner shadow centred on the inner corner of the visible frame
            fx = x + n if name.endswith("left") else x
            fy = y + n if name.startswith("top") else y
            parts.append(rect(x, y, w, h, sh.grad("radial", {"cx": fx, "cy": fy, "r": PAD + B}, SH_STOPS)))
        elif name != "center":
            if name == "top":
                g = {"x1": x, "y1": y + n, "x2": x, "y2": y}
            elif name == "bottom":
                g = {"x1": x, "y1": y, "x2": x, "y2": y + n}
            elif name == "left":
                g = {"x1": x + n, "y1": y, "x2": x, "y2": y}
            else:
                g = {"x1": x, "y1": y, "x2": x + n, "y2": y}
            parts.append(rect(x, y, w, h, sh.grad("linear", g, SH_STOPS)))
        # --- visible frame ------------------------------------------------------------
        if name == "center":
            parts.append(rect(x, y, w, h, title, TITLE_ALPHA))
        elif name in ("top", "bottom"):
            by = y + pad if name == "top" else y
            parts.append(rect(x, by, w, B, border_col, border_op))
            if name == "top" and accent:
                ga = sh.grad("linear", {"x1": x, "y1": by, "x2": x + w, "y2": by},
                             [(0, C["orange"], 1), (0.035, C["orange"], 1), (0.12, C["orange"], 0), (1, C["orange"], 0)])
                parts.append(rect(x, by, w, B, ga))
        elif name in ("left", "right"):
            bx = x + pad if name == "left" else x
            parts.append(rect(bx, y, B, h, border_col, border_op))
        else:  # corners: rounded visible corner (radius R) sitting at the inner side
            left, top = name.endswith("left"), name.startswith("top")
            # the visible corner square is B x B at the inner edge; draw a rounded
            # bracket that extends R px into the neighbouring edges via the title fill.
            ix = x + (pad if left else 0)
            iy = y + (pad if top else 0)
            parts.append(rect(ix, iy, B, B, border_col, border_op))
        sh.add(prefix + name, "".join(parts))


def build_decoration():
    sh = Sheet()
    orange_border = (C["orange"], 0.55)
    muted = (C["border"], 1.0)
    decoration(sh, "decoration-", *orange_border, accent=True)
    decoration(sh, "decoration-inactive-", *muted, accent=False)
    decoration(sh, "decoration-maximized-", *orange_border, accent=False, maximized=True)
    decoration(sh, "decoration-maximized-inactive-", *muted, accent=False, maximized=True)
    sh.items.append('<rect id="hint-stretch-borders" x="0" y="%d" width="2" height="2" fill="#f0f" fill-opacity="0.5"/>' % sh.y)
    sh.y += 4
    (OUT / "decoration.svg").write_text(sh.svg())


# --------------------------------------------------------------------------
# Buttons (16 x 16, glyph drawn with 1.5px strokes)
# --------------------------------------------------------------------------
S = 16
GLYPHS = {
    "close": '<path d="M5,5 L11,11 M11,5 L5,11"/>',
    "minimize": '<path d="M4.5,10.5 L11.5,10.5"/>',
    "maximize": '<rect x="4.5" y="4.5" width="7" height="7"/>',
    "restore": '<path d="M6.5,4.5 L11.5,4.5 L11.5,9.5"/><rect x="4.5" y="6.5" width="5" height="5"/>',
    "alldesktops": '<circle cx="8" cy="8" r="3"/><circle cx="8" cy="8" r="0.6"/>',
    "keepabove": '<path d="M4.5,9.5 L8,6 L11.5,9.5"/>',
    "keepbelow": '<path d="M4.5,6.5 L8,10 L11.5,6.5"/>',
    "shade": '<path d="M4.5,5.5 L11.5,5.5 M5.5,8.5 L10.5,8.5"/>',
    "help": '<path d="M6,6.2 C6,4.6 10,4.6 10,6.4 C10,7.8 8,7.8 8,9.4"/><circle cx="8" cy="11.6" r="0.4"/>',
}

STATES = {
    #            bg colour, bg alpha, glyph colour, glyph alpha
    "active": (None, 0, C["textMuted"], 1.0),
    "hover": (C["surfaceHover"], 1.0, C["orange"], 1.0),
    "pressed": (C["orangeDim"], 0.55, C["text"], 1.0),
    "inactive": (None, 0, C["textDisabled"], 1.0),
    "deactivated": (None, 0, C["textDisabled"], 0.45),
}
CLOSE_STATES = dict(STATES, hover=(C["error"], 0.9, C["onAccent"], 1.0), pressed=(C["error"], 0.6, C["text"], 1.0))


def build_button(name):
    states = CLOSE_STATES if name == "close" else STATES
    items = []
    for i, (state, (bg, bga, fg, fga)) in enumerate(states.items()):
        x = i * (S + 4)
        body = rect(x, 0, S, S, bg or "#000000", bga, 'rx="%d"' % G["radiusControl"])
        stroke = 'fill="none" stroke="%s" stroke-opacity="%.2f" stroke-width="1.5" stroke-linecap="square"' % (fg, fga)
        body += '<g transform="translate(%d,0)" %s>%s</g>' % (x, stroke, GLYPHS[name])
        items.append('<g id="%s-center">%s</g>' % (state, body))
        # toggled buttons (on all desktops / keep above / below / shade) use "pressed"
    w = len(states) * (S + 4)
    svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<!-- Generated by aurorae/tools/build.py from tokens.json - do not edit by hand. -->\n'
           '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d">\n%s\n</svg>\n' % (w, S, "\n".join(items)))
    (OUT / ("%s.svg" % name)).write_text(svg)


def rgb(h):
    h = h.lstrip("#")
    return "%d,%d,%d" % tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def build_rc():
    rc = f"""# Generated by aurorae/tools/build.py from tokens.json
[General]
ActiveTextColor={rgb(C["text"])}
InactiveTextColor={rgb(C["textMuted"])}
UseTextShadow=false
TitleAlignment=Left
TitleVerticalAlignment=Center
Animation={T["motion"]["fast"]}
Shadow=true
LeftButtons=M
RightButtons=IAX
DecorationPosition=0

[Layout]
BorderLeft=1
BorderRight=1
BorderBottom=1
TitleEdgeTop=6
TitleEdgeBottom=6
TitleEdgeLeft=8
TitleEdgeRight=8
TitleEdgeTopMaximized=5
TitleEdgeBottomMaximized=5
TitleEdgeLeftMaximized=6
TitleEdgeRightMaximized=6
TitleBorderLeft=6
TitleBorderRight=6
TitleHeight=20
ButtonWidth=22
ButtonHeight=22
ButtonSpacing=4
ButtonMarginTop=0
ExplicitButtonSpacer=8
PaddingTop={PAD}
PaddingBottom={PAD}
PaddingLeft={PAD}
PaddingRight={PAD}
"""
    (OUT / "aperture-osrc").write_text(rc)
    (OUT / "metadata.desktop").write_text(f"""[Desktop Entry]
Name=Aperture OS
Comment=Aperture OS window decoration - dark title bar, 1px frame, orange focus
X-KDE-PluginInfo-Author=Quatzler
X-KDE-PluginInfo-Name=aperture-os
X-KDE-PluginInfo-Version={T["version"]}
X-KDE-PluginInfo-License=GPL-3.0-or-later
X-KDE-PluginInfo-EnabledByDefault=true
""")


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    build_decoration()
    for name in GLYPHS:
        build_button(name)
    build_rc()
    print("built", OUT)


if __name__ == "__main__":
    main()
