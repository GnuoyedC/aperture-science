# Aperture iris: 8 blades (same geometry as globaltheme/icons/aperture-os.svg).
# Each blade: point A -> line -> point B -> clockwise arc (r=48 around 50,50) -> point C.
BLADES = [((64.900, 62.111), (64.900, 95.629), (32.367, 94.644)),
          ((51.972, 69.100), (28.271, 92.800), (5.964, 69.100)),
          ((37.889, 64.900), (4.371, 64.900), (5.356, 32.367)),
          ((30.900, 51.972), (7.200, 28.271), (30.900, 5.964)),
          ((35.100, 37.889), (35.100, 4.371), (67.633, 5.356)),
          ((48.028, 30.900), (71.729, 7.200), (94.036, 30.900)),
          ((62.111, 35.100), (95.629, 35.100), (94.644, 67.633)),
          ((69.100, 48.028), (92.800, 71.729), (69.100, 94.036))]


def blade_polygon(blade, scale, steps=48):
    import math
    a, b, c = blade
    ab = math.atan2(b[1] - 50, b[0] - 50)
    ac = math.atan2(c[1] - 50, c[0] - 50)
    while ac < ab:
        ac += 2 * math.pi
    pts = [a, b] + [(50 + 48 * math.cos(ab + (ac - ab) * i / steps), 50 + 48 * math.sin(ab + (ac - ab) * i / steps))
                    for i in range(1, steps + 1)]
    return [(x * scale, y * scale) for x, y in pts]


def render_iris(size, core=True):
    """RGBA image of the iris (supersampled), orange blades + small blue core."""
    from PIL import Image, ImageDraw, ImageFilter
    ss = 8
    big = size * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    orange = tuple(int(C["orange"][i:i + 2], 16) for i in (1, 3, 5))
    for bl in BLADES:
        d.polygon(blade_polygon(bl, big / 100), fill=orange + (255,))
    if core:
        blue = tuple(int(C["blueBright"][i:i + 2], 16) for i in (1, 3, 5))
        glow = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        gd = ImageDraw.Draw(glow)
        r = big * 0.11
        gd.ellipse((big / 2 - r, big / 2 - r, big / 2 + r, big / 2 + r), fill=blue + (150,))
        glow = glow.filter(ImageFilter.GaussianBlur(big * 0.035))
        img = Image.alpha_composite(img, glow)
        d = ImageDraw.Draw(img)
        r = big * 0.045
        d.ellipse((big / 2 - r, big / 2 - r, big / 2 + r, big / 2 + r), fill=(235, 250, 255, 255))
    return img.resize((size, size), Image.LANCZOS)


def halfblock_art(cols):
    """Text logo: the iris as half-block characters.

    Each character cell holds two square "pixels" (upper/lower half). $1 = orange blades,
    $2 = blue core. Coverage is sampled from the supersampled vector render, so the
    blade edges and the gaps between the blades stay clean."""
    from PIL import Image
    n = cols                                  # n x n pixels -> n columns, n/2 rows
    blades = render_iris(n * 8, core=False).resize((n, n), Image.BOX).getchannel("A")
    rows = []
    cx = cy = (n - 1) / 2
    core_r = n * 0.055
    for y in range(0, n, 2):
        line, cur = "", None
        for x in range(n):
            px = []
            for yy in (y, y + 1):
                if yy >= n:
                    px.append(None)
                elif (x - cx) ** 2 + (yy - cy) ** 2 <= core_r ** 2:
                    px.append("core")
                elif blades.getpixel((x, yy)) > 120:
                    px.append("blade")
                else:
                    px.append(None)
            top, bot = px
            if top is None and bot is None:
                line += " "
                continue
            kind = "core" if "core" in px else "blade"
            colour = "$2" if kind == "core" else "$1"
            if colour != cur:
                line += colour
                cur = colour
            t, b_ = top == kind, bot == kind
            line += "█" if t and b_ else "▀" if t else "▄"
        rows.append(line.rstrip())
    return "\n".join(rows) + "\n"


