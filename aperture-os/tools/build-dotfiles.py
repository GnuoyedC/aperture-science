#!/usr/bin/env python3
"""Generate the Aperture OS terminal dotfiles from design/tokens.json.

  dotfiles/kitty/aperture.conf        colours, opacity, blur, tab bar, borders
  dotfiles/starship/aperture.toml     prompt (your previous module set, Aperture palette)
  dotfiles/fastfetch/config.jsonc     + aperture-logo.txt

Usage: tools/build-dotfiles.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design/tokens.json").read_text())
C, A, F = T["color"], T["alpha"], T["font"]
OUT = ROOT / "dotfiles"
HEAD = "# Generated by tools/build-dotfiles.py from design/tokens.json - edit the tokens, not this file.\n"

# ANSI palette: normal / bright. Magenta is mapped to Aperture orange.
ANSI = [
    ("black", C["surfaceElevated"], C["borderStrong"]),
    ("red", C["error"], "#FF7A7A"),
    ("green", C["success"], "#7FE3AE"),
    ("yellow", C["warning"], "#FFC94D"),
    ("blue", C["blue"], C["blueBright"]),
    ("magenta", C["orange"], C["orangeBright"]),
    ("cyan", "#2CC5C9", "#7FE0E3"),
    ("white", "#B8C6CE", C["text"]),
]


def kitty():
    lines = [HEAD, "# Included from kitty.conf via `include aperture.conf` (see dotfiles/README.md).", ""]
    lines += [
        "# --- surface: tinted safety glass ---",
        "background            %s" % C["background"],
        "foreground            %s" % C["text"],
        "background_opacity    %.2f" % A["terminal"],
        "background_blur       24",
        "dynamic_background_opacity yes",
        "",
        "# --- cursor / selection (orange = interaction) ---",
        "cursor                %s" % C["orange"],
        "cursor_text_color     %s" % C["onAccent"],
        "selection_foreground  %s" % C["text"],
        "selection_background  #47301A",
        "url_color             %s" % C["blue"],
        "url_style             single",
        "",
        "# --- ANSI colours (magenta = Aperture orange) ---",
    ]
    for i, (name, normal, bright) in enumerate(ANSI):
        lines.append("color%-2d %s   # %s" % (i, normal, name))
        lines.append("color%-2d %s   # bright %s" % (i + 8, bright, name))
    lines += [
        "",
        "# --- window chrome ---",
        "window_padding_width  6 10",
        "active_border_color   %s" % C["orange"],
        "inactive_border_color %s" % C["border"],
        "bell_border_color     %s" % C["warning"],
        "",
        "# --- tab bar: technical, flat ---",
        "tab_bar_edge          top",
        "tab_bar_style         separator",
        'tab_separator         "  │  "',
        "tab_bar_background    %s" % C["background"],
        "active_tab_background   %s" % C["surfaceElevated"],
        "active_tab_foreground   %s" % C["orangeBright"],
        "active_tab_font_style   bold",
        "inactive_tab_background %s" % C["background"],
        "inactive_tab_foreground %s" % C["textMuted"],
        "inactive_tab_font_style normal",
        'tab_title_template    "{index}: {title}"',
        "",
        "# --- marks ---",
        "mark1_foreground %s" % C["onAccent"],
        "mark1_background %s" % C["orange"],
        "mark2_foreground %s" % C["onAccent"],
        "mark2_background %s" % C["blue"],
        "",
    ]
    (OUT / "kitty/aperture.conf").write_text("\n".join(lines))


