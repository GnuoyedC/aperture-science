#!/usr/bin/env python3
"""Build the shared parts of the Aperture OS widgets from tokens.json.

Every plasmoid package has to be self-contained, so the shared QML files are
copied into each package instead of being imported from a common module.

Generated:
  shared/Tokens.qml                 colours, alphas, geometry, fonts, motion
  shared/images/aperture-logo.svg   emblem tinted with the token text colour

Synchronised into every package (<id>/contents/ui/ and <id>/contents/images/):
  shared/*.qml, shared/images/*

Edit shared/*.qml (never the copies inside the packages), then run
  tools/build.py
Only the Python standard library is used; only tokens.json is read.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"
PACKAGES = ("aperture-os.testchamber", "aperture-os.sysmonitor", "aperture-os.notice")
T = json.loads((ROOT / "tokens.json").read_text(encoding="utf-8"))

HEADER = "// GENERATED by tools/build.py from %s - do not edit the copy inside a package.\n"


def qml_tokens():
    c, a, g, f, m = T["color"], T["alpha"], T["geometry"], T["font"], T["motion"]
    out = [HEADER % "tokens.json", "import QtQuick\n\n",
           "// Aperture OS design tokens (v%s). Instantiate once per plasmoid and\n" % T["version"],
           "// pass it down as `tk` to the shared components.\n",
           "QtObject {\n"]
    out.append("    // ---- colours\n")
    for k, v in c.items():
        out.append('    readonly property color %s: "%s"\n' % (k, v))
    out.append("\n    // ---- surface opacity (0..1)\n")
    for k, v in a.items():
        out.append("    readonly property real alpha%s: %s\n" % (k[0].upper() + k[1:], v))
    out.append("\n    // ---- geometry (px)\n")
    for k, v in g.items():
        out.append("    readonly property int %s: %s\n" % (k, v))
    out.append("\n    // ---- fonts\n")
    ui = [f["ui"], f["uiFallback"], "sans-serif"]
    mono = [f["mono"], f["monoFallback"], "Noto Sans Mono", "monospace"]
    display = [f.get("display", f["ui"]), f.get("displayFallback", f["ui"]), f["uiFallback"], "sans-serif"]
    out.append("    readonly property var displayCandidates: %s\n" % json.dumps(display))
    out.append("    readonly property string displayFamily: pickFont(displayCandidates)\n")
    out.append("    readonly property var uiCandidates: %s\n" % json.dumps(ui))
    out.append("    readonly property var monoCandidates: %s\n" % json.dumps(mono))
    out.append("    readonly property string uiFamily: pickFont(uiCandidates)\n")
    out.append("    readonly property string monoFamily: pickFont(monoCandidates)\n")
    out.append("    readonly property real uiSize: %s\n" % f["uiSize"])
    out.append("    // derived sizes (pt): small technical labels, values, large values\n")
    out.append("    readonly property real labelSize: Math.round(uiSize * 0.78 * 2) / 2\n")
    out.append("    readonly property real valueSize: uiSize\n")
    out.append("    readonly property real largeSize: Math.round(uiSize * 1.4)\n")
    out.append("\n    // ---- motion (ms)\n")
    for k, v in m.items():
        if k == "reduceMotion":
            out.append("    readonly property bool reduceMotionDefault: %s\n" % ("true" if v else "false"))
        else:
            out.append("    readonly property int motion%s: %s\n" % (k[0].upper() + k[1:], v))
    out.append("""
    // ---- helpers
    function pickFont(candidates) {
        const available = Qt.fontFamilies()
        for (let i = 0; i < candidates.length; ++i) {
            if (available.indexOf(candidates[i]) >= 0)
                return candidates[i]
        }
        return candidates[candidates.length - 1]
    }
    function alpha(c, a) { return Qt.rgba(c.r, c.g, c.b, a) }
}
""")
    return "".join(out)


def logo_svg():
    src = (SHARED / "aperture-logo.template.svg").read_text(encoding="utf-8")
    return src.replace("@FILL@", T["color"]["text"])


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


def main():
    write(SHARED / "Tokens.qml", qml_tokens())
    write(SHARED / "images" / "aperture-logo.svg", logo_svg())
    for pkg in PACKAGES:
        base = ROOT / pkg / "contents"
        if not base.is_dir():
            raise SystemExit("missing package %s" % pkg)
        for qml in sorted(SHARED.glob("*.qml")):
            text = qml.read_text(encoding="utf-8")
            if not text.startswith("// GENERATED"):
                text = HEADER % ("shared/" + qml.name) + text
            write(base / "ui" / qml.name, text)
        for img in sorted((SHARED / "images").glob("*")):
            dst = base / "images" / img.name
            dst.parent.mkdir(parents=True, exist_ok=True)
            if not dst.exists() or dst.read_bytes() != img.read_bytes():
                shutil.copyfile(img, dst)
                print("wrote", dst.relative_to(ROOT))


if __name__ == "__main__":
    main()
