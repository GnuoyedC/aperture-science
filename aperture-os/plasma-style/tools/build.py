#!/usr/bin/env python3
"""Build the Aperture OS Plasma Style (desktoptheme) from tokens.json.

Only the SVGs that define the Aperture look are generated. Everything else
(scrollbars, sliders, checkboxes, ...) falls back to Plasma's default theme,
which picks up the Aperture colour scheme automatically - no duplicated assets.

Generated (into ../aperture-os/):
  widgets/panel-background.svg   panel, location aware orange accent line
  dialogs/background.svg         popups, launcher, notifications, KRunner
  widgets/background.svg         desktop widgets (corner brackets)
  widgets/tooltip.svg            tooltips (almost opaque)
  widgets/plasmoidheading.svg    popup header / footer strips
  widgets/viewitem.svg           list hover / selection (left signal bar)
  widgets/tasks.svg              task manager indicators
  opaque/...  solid/...          variants without transparency
  colors, plasmarc, metadata.json
Usage: tools/build.py
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "aperture-os"
T = json.loads((ROOT / "tokens.json").read_text())
C, A, G = T["color"], T["alpha"], T["geometry"]

SIDES = ("top", "bottom", "left", "right")


# --------------------------------------------------------------------------
# SVG helpers
# --------------------------------------------------------------------------
def paint(color, alpha=1.0):
    return 'fill="%s" fill-opacity="%.3f"' % (color, alpha)


class Canvas:
    """Collects named elements, laid out row by row on one sheet."""

    def __init__(self):
        self.defs, self.items = [], []
        self.y = 0
        self.width = 0
        self._grad = 0

    def row(self, height, width):
        y = self.y
        self.y += height + 4
        self.width = max(self.width, width)
        return y

    def gradient(self, x1, y1, x2, y2, stops):
        self._grad += 1
        gid = "g%d" % self._grad
        s = "".join('<stop offset="%.4f" stop-color="%s" stop-opacity="%.3f"/>' % st for st in stops)
        self.defs.append('<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%.2f" y1="%.2f" '
                         'x2="%.2f" y2="%.2f">%s</linearGradient>' % (gid, x1, y1, x2, y2, s))
        return "url(#%s)" % gid

    def radial(self, cx, cy, r, stops):
        self._grad += 1
        gid = "g%d" % self._grad
        s = "".join('<stop offset="%.4f" stop-color="%s" stop-opacity="%.3f"/>' % st for st in stops)
        self.defs.append('<radialGradient id="%s" gradientUnits="userSpaceOnUse" cx="%.2f" cy="%.2f" '
                         'r="%.2f">%s</radialGradient>' % (gid, cx, cy, r, s))
        return "url(#%s)" % gid

    def element(self, eid, body):
        self.items.append('<g id="%s">%s</g>' % (eid, body))

    def hint(self, eid, x, y, w, h):
        self.items.append('<rect id="%s" x="%d" y="%d" width="%d" height="%d" fill="#ff00ff" fill-opacity="0.5"/>'
                          % (eid, x, y, w, h))

    def svg(self):
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- Generated by plasma-style/tools/build.py from tokens.json - do not edit by hand. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">\n'
                '<defs>%s</defs>\n%s\n</svg>\n'
                % (self.width, self.y, self.width, self.y, "".join(self.defs), "\n".join(self.items)))


def corner_paths(n, r, bw, fx, fy, ox, oy):
    """Outer and inner outline of a top-left corner cell, mirrored by fx/fy.

    Returns (outer, inner) path strings in absolute sheet coordinates."""

    def P(x, y):
        return (ox + (n - x if fx else x), oy + (n - y if fy else y))

    sweep = 1 if (fx == fy) else 0

    def shape(off, rad):
        pts = []
        a = P(off, n)
        if rad > 0:
            b, c = P(off, off + rad), P(off + rad, off)
            pts.append("M%.2f,%.2f L%.2f,%.2f A%.2f,%.2f 0 0 %d %.2f,%.2f" % (a + b + (rad, rad, sweep) + c))
        else:
            b = P(off, off)
            pts.append("M%.2f,%.2f L%.2f,%.2f" % (a + b))
        d, e = P(n, off), P(n, n)
        pts.append("L%.2f,%.2f L%.2f,%.2f Z" % (d + e))
        return " ".join(pts)

    return shape(0, r), shape(bw, max(r - bw, 0))


def frame(cv, prefix, *, n, c=8, fill, alpha, radius=0, border=None, corner=None,
          accent=None, bar=None, line=None, margins=None, shadow=None):
    """Draw a 9-slice frame.

    border : dict side -> (color, alpha) for 1px border lines
    corner : (color, alpha) colour of the border inside corner cells
             (brighter than the edges -> technical corner brackets)
    accent : (side, color, stops) gradient line on one edge (stretched)
    bar    : (side, color, alpha, width) solid signal bar on one edge
    line   : (side, color, alpha, width, (f0, f1)) centred indicator line
    margins: dict side -> content margin
    shadow : (size, alpha)
    """
    border = border or {}
    pre = prefix + "-" if prefix else ""
    sz = n + c + n
    y0 = cv.row(sz + (2 * shadow[0] if shadow else 0), sz + 4 * n + (2 * shadow[0] if shadow else 0))
    x0 = 0
    if shadow:
        _shadow(cv, pre, shadow, n, c, x0, y0)
        x0 += 2 * shadow[0] + 4
    bw = G["borderWidth"]
    cells = {
        "topleft": (x0, y0, n, n), "top": (x0 + n, y0, c, n), "topright": (x0 + n + c, y0, n, n),
        "left": (x0, y0 + n, n, c), "center": (x0 + n, y0 + n, c, c), "right": (x0 + n + c, y0 + n, n, c),
        "bottomleft": (x0, y0 + n + c, n, n), "bottom": (x0 + n, y0 + n + c, c, n),
        "bottomright": (x0 + n + c, y0 + n + c, n, n),
    }
    fill_attr = paint(fill, alpha)

    for name, (x, y, w, h) in cells.items():
        parts = []
        if name in ("topleft", "topright", "bottomleft", "bottomright"):
            fx, fy = name.endswith("right"), name.startswith("bottom")
            sv, sh = ("bottom" if fy else "top"), ("right" if fx else "left")
            both = sv in border and sh in border
            outer, inner = corner_paths(n, radius, bw if both else 0, fx, fy, x, y)
            parts.append('<path d="%s" %s/>' % (inner if both else outer, fill_attr))
            if both:
                col, al = corner or border[sv]
                parts.append('<path d="%s %s" fill-rule="evenodd" %s/>' % (outer, inner, paint(col, al)))
            else:  # border on one side only: plain strip, no bracket
                for side in (sv, sh):
                    if side in border:
                        bx, by, bw_, bh = _edge_strip(side, x, y, w, h, bw)
                        parts.append('<rect x="%d" y="%d" width="%d" height="%d" %s/>'
                                     % (bx, by, bw_, bh, paint(*border[side])))
        else:
            parts.append('<rect x="%d" y="%d" width="%d" height="%d" %s/>' % (x, y, w, h, fill_attr))
            if name in border:
                col, al = border[name]
                bx, by, bw_, bh = _edge_strip(name, x, y, w, h, bw)
                parts.append('<rect x="%d" y="%d" width="%d" height="%d" %s/>' % (bx, by, bw_, bh, paint(col, al)))
        if accent and name == accent[0]:
            side, col, stops = accent
            horiz = side in ("top", "bottom")
            gx1, gy1, gx2, gy2 = (x, y, x + w, y) if horiz else (x, y, x, y + h)
            grad = cv.gradient(gx1, gy1, gx2, gy2, [(o, cc, a) for o, cc, a in stops])
            for k, a in ((0, 1.0), (1, 0.35)):  # 1px line + 1px soft glow towards the content
                bx, by, bw_, bh = _edge_strip(side, x, y, w, h, 1, k)
                parts.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" opacity="%.2f"/>'
                             % (bx, by, bw_, bh, grad, a))
        if bar:
            side, col, al, width = bar
            touches = {"left": name.endswith("left"), "right": name.endswith("right"),
                       "top": name.startswith("top"), "bottom": name.startswith("bottom")}[side]
            if touches:
                bx, by, bw_, bh = _edge_strip(side, x, y, w, h, width)
                parts.append('<rect x="%d" y="%d" width="%d" height="%d" %s/>' % (bx, by, bw_, bh, paint(col, al)))
        if line and name == line[0]:
            side, col, al, width, (f0, f1) = line
            horiz = side in ("top", "bottom")
            gx1, gy1, gx2, gy2 = (x, y, x + w, y) if horiz else (x, y, x, y + h)
            e = 0.06
            grad = cv.gradient(gx1, gy1, gx2, gy2, [(0, col, 0), (max(f0 - e, 0), col, 0), (f0, col, al),
                                                    (f1, col, al), (min(f1 + e, 1), col, 0), (1, col, 0)])
            bx, by, bw_, bh = _edge_strip(side, x, y, w, h, width)
            parts.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>' % (bx, by, bw_, bh, grad))
        cv.element(pre + name, "".join(parts))

    if margins:
        hx = x0 + sz + 4
        for i, side in enumerate(SIDES):
            m = margins[side]
            if side in ("top", "bottom"):
                cv.hint(pre + "hint-%s-margin" % side, hx + i * (n + 2), y0, 1, m)
            else:
                cv.hint(pre + "hint-%s-margin" % side, hx + i * (n + 2), y0, m, 1)


def _edge_strip(side, x, y, w, h, width, k=0):
    """Rect of `width` px lying on `side` of a cell, k px inwards."""
    if side == "top":
        return x, y + k, w, width
    if side == "bottom":
        return x, y + h - width - k, w, width
    if side == "left":
        return x + k, y, width, h
    return x + w - width - k, y, width, h


def _shadow(cv, pre, shadow, n, c, x0, y0):
    s, a = shadow
    stops = [(0, "#000000", a), (0.35, "#000000", a * 0.45), (0.7, "#000000", a * 0.12), (1, "#000000", 0)]
    cs = c
    tot = s + cs + s
    cells = {
        "topleft": (x0, y0, s, s, ("r", x0 + s, y0 + s)),
        "top": (x0 + s, y0, cs, s, ("l", x0 + s, y0 + s, x0 + s, y0)),
        "topright": (x0 + s + cs, y0, s, s, ("r", x0 + s + cs, y0 + s)),
        "left": (x0, y0 + s, s, cs, ("l", x0 + s, y0 + s, x0, y0 + s)),
        "right": (x0 + s + cs, y0 + s, s, cs, ("l", x0 + s + cs, y0 + s, x0 + tot, y0 + s)),
        "bottomleft": (x0, y0 + s + cs, s, s, ("r", x0 + s, y0 + s + cs)),
        "bottom": (x0 + s, y0 + s + cs, cs, s, ("l", x0 + s, y0 + s + cs, x0 + s, y0 + tot)),
        "bottomright": (x0 + s + cs, y0 + s + cs, s, s, ("r", x0 + s + cs, y0 + s + cs)),
    }
    for name, (x, y, w, h, g) in cells.items():
        if g[0] == "r":
            fill = cv.radial(g[1], g[2], s, stops)
        else:
            fill = cv.gradient(g[1], g[2], g[3], g[4], stops)
        cv.element(pre + "shadow-" + name, '<rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>' % (x, y, w, h, fill))
    cv.element(pre + "shadow-center", '<rect x="%d" y="%d" width="%d" height="%d" fill="#000000" fill-opacity="0"/>'
               % (x0 + s, y0 + s, cs, cs))
    for i, side in enumerate(SIDES):
        # The shadow casts a little more downwards than upwards.
        m = {"top": s - 3, "bottom": s + 2, "left": s, "right": s}[side]
        if side in ("top", "bottom"):
            cv.hint(pre + "shadow-hint-%s-margin" % side, x0 + i * 3, y0 + tot + 2, 1, m)
        else:
            cv.hint(pre + "shadow-hint-%s-margin" % side, x0 + i * 3, y0 + tot + 2, m, 1)


def all_borders(color, alpha=1.0):
    return {s: (color, alpha) for s in SIDES}


def write(rel, cv, extra_hints=()):
    for h in extra_hints:
        cv.hint(h, cv.width + 2, 0, 2, 2)
        cv.width += 6
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(cv.svg())


