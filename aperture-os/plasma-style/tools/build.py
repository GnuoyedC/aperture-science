ACCENT = [(0, C["orange"], 1.0), (0.035, C["orange"], 1.0), (0.11, C["border"], 1.0), (1, C["border"], 1.0)]


def panel(alpha):
    cv = Canvas()
    n = 6
    m = {s: 2 for s in SIDES}
    base = dict(n=n, fill=C["background"], alpha=alpha, radius=G["radiusFrame"],
                border=all_borders(C["border"]), corner=(C["borderStrong"], 1.0), margins=m)
    # Floating / generic panel: full border, brighter corner brackets.
    frame(cv, "", shadow=(10, 0.30), **base)
    # Panels docked to a screen edge: accent line on the edge facing the desktop.
    facing = {"north": "bottom", "south": "top", "west": "right", "east": "left"}
    for loc, side in facing.items():
        frame(cv, loc, accent=(side, C["orange"], ACCENT), **base)
    write("widgets/panel-background.svg", cv, ["hint-stretch-borders"])


def dialog(alpha, rel="dialogs/background.svg", margin=8):
    cv = Canvas()
    frame(cv, "", n=8, fill=C["surface"], alpha=alpha, radius=G["radiusFrame"],
          border=all_borders(C["border"]), corner=(C["borderStrong"], 1.0),
          margins={s: margin for s in SIDES}, shadow=(12, 0.38))
    write(rel, cv, ["hint-stretch-borders"])


def widget_bg(alpha):
    cv = Canvas()
    frame(cv, "", n=10, fill=C["background"], alpha=alpha, radius=G["radiusFrame"],
          border=all_borders(C["border"], 0.85), corner=(C["blueDim"], 1.0),
          margins={s: 12 for s in SIDES}, shadow=(8, 0.25))
    write("widgets/background.svg", cv, ["hint-stretch-borders"])


def tooltip(alpha):
    cv = Canvas()
    frame(cv, "", n=6, fill=C["surfaceElevated"], alpha=alpha, radius=G["radiusControl"],
          border=all_borders(C["borderStrong"]), margins={s: 6 for s in SIDES}, shadow=(8, 0.30))
    write("widgets/tooltip.svg", cv, ["hint-stretch-borders"])


def heading():
    cv = Canvas()
    frame(cv, "header", n=4, fill=C["surfaceElevated"], alpha=0.55,
          border={"bottom": (C["border"], 1.0)}, margins={s: 6 for s in SIDES})
    frame(cv, "footer", n=4, fill=C["surfaceElevated"], alpha=0.55,
          border={"top": (C["border"], 1.0)}, margins={s: 6 for s in SIDES})
    # plasmoidheading reads its margins from the un-prefixed hints
    for i, side in enumerate(SIDES):
        w, h = (1, 6) if side in ("top", "bottom") else (6, 1)
        cv.hint("hint-%s-margin" % side, cv.width + 4 + i * 8, 0, w, h)
    cv.width += 40
    write("widgets/plasmoidheading.svg", cv, ["hint-stretch-borders"])


def viewitem():
    cv = Canvas()
    m = {s: 4 for s in SIDES}
    common = dict(n=4, radius=0, margins=m)
    frame(cv, "normal", fill=C["surface"], alpha=0.0, **common)
    frame(cv, "hover", fill=C["surfaceHover"], alpha=0.85, bar=("left", C["orange"], 0.75, 2),
          border={"top": (C["border"], 0.5), "bottom": (C["border"], 0.5), "right": (C["border"], 0.5)}, **common)
    frame(cv, "selected", fill=C["orange"], alpha=0.16, bar=("left", C["orange"], 1.0, 2),
          border=all_borders(C["orange"], 0.40), **common)
    frame(cv, "selected+hover", fill=C["orange"], alpha=0.24, bar=("left", C["orange"], 1.0, 2),
          border=all_borders(C["orange"], 0.55), **common)
    write("widgets/viewitem.svg", cv, ["hint-tile-center"])


def tasks():
    """Task manager: indicator line on the screen-edge side of the panel."""
    cv = Canvas()
    m = {s: 2 for s in SIDES}
    edge = {"": "bottom", "south": "bottom", "north": "top", "west": "left", "east": "right"}
    for loc, side in edge.items():
        p = (loc + "-") if loc else ""
        common = dict(n=3, radius=0, margins=m)
        frame(cv, p + "normal", fill=C["surface"], alpha=0.0,
              line=(side, C["textMuted"], 0.85, 2, (0.38, 0.62)), **common)
        frame(cv, p + "minimized", fill=C["surface"], alpha=0.0,
              line=(side, C["textDisabled"], 0.8, 2, (0.42, 0.58)), **common)
        frame(cv, p + "hover", fill=C["surfaceHover"], alpha=0.75,
              line=(side, C["blueBright"], 0.9, 2, (0.2, 0.8)), **common)
        frame(cv, p + "focus", fill=C["orange"], alpha=0.12,
              line=(side, C["orange"], 1.0, 2, (0.08, 0.92)), **common)
        frame(cv, p + "attention", fill=C["warning"], alpha=0.14,
              line=(side, C["warning"], 1.0, 2, (0.08, 0.92)), **common)
        frame(cv, p + "progress", fill=C["blue"], alpha=0.18, **common)
    write("widgets/tasks.svg", cv, ["hint-stretch-borders"])


