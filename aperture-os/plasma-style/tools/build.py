def colors_file():
    src = ROOT / "ApertureOS.colors"
    if not src.exists():
        raise SystemExit("ApertureOS.colors missing - run tools/build-all.sh (copies it from colors/)")
    (OUT / "colors").write_text(src.read_text())


def metadata():
    meta = {
        "KPlugin": {
            "Authors": [{"Name": "Quatzler"}],
            "Category": "",
            "Description": "Aperture OS - tinted safety glass for Plasma 6",
            "Id": "aperture-os",
            "License": "GPL-3.0-or-later",
            "Name": "Aperture OS",
            "Version": T["version"],
            "Website": "",
        },
        "X-Plasma-API-Minimum-Version": "6.0",
    }
    (OUT / "metadata.json").write_text(json.dumps(meta, indent=4) + "\n")
    (OUT / "plasmarc").write_text(
        "# Generated by tools/build.py\n"
        "[ContrastEffect]\nenabled=true\ncontrast=0.9\nintensity=0.85\nsaturation=1.1\n\n"
        "[AdaptiveTransparency]\nenabled=true\n\n"
        "[BlurBehindEffect]\nenabled=true\n")


def main():
    global OUT
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    colors_file()
    metadata()
    panel(A["panel"])
    dialog(A["glass"])
    widget_bg(A["widget"])
    tooltip(A["tooltip"])
    heading()
    viewitem()
    tasks()
    # Variants without compositing (opaque/) and for the "opaque" panel mode (solid/).
    root = OUT
    for sub in ("opaque", "solid"):
        OUT = root / sub
        panel(1.0)
        dialog(1.0)
        widget_bg(1.0)
        tooltip(1.0)
    OUT = root
    print("built", OUT)


if __name__ == "__main__":
    main()
