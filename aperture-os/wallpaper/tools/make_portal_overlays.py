#!/usr/bin/env python3
"""Cut the light sources of the "Test chamber with portals" motif out of the photo.

The scene brightens the photo's own pixels (portal rings, LED strips) instead of
drawing shapes over them, so everything sits exactly where the photo has it.

Writes aperture-os.chamber/contents/images/overlays/portals/*.png and
contents/ui/scenes/PortalOverlays.qml (rects relative to the 1672x941 art).
Needs Pillow; output is checked in.  Usage: tools/make_portal_overlays.py
"""
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "aperture-os.chamber" / "contents"
SRC = ROOT / "Images" / "Aperture Portal Chamber.png"
OUT = PKG / "images" / "overlays" / "portals"
W0, H0 = 1672, 941   # art size the scene coordinates refer to


def smooth(e0, e1, x):
    t = max(0.0, min(1.0, (x - e0) / (e1 - e0)))
    return t * t * (3 - 2 * t)


def orange(r, g, b):
    return smooth(40, 90, r - g) * smooth(120, 190, r) * (1 - smooth(90, 150, b))


def cyan(r, g, b):
    return smooth(60, 120, b - r) * smooth(130, 200, b) * smooth(70, 130, g)


# name -> (box px, colour mask, gain, lift, halo rgb, halo radius, halo alpha)
PARTS = {
    "orange": ((1100, 295, 1170, 450), orange, 1.4, (70, 30, 0), (255, 154, 61), 7, 0.55),
    "blue": ((795, 585, 905, 700), cyan, 1.35, (0, 30, 60), (92, 205, 247), 7, 0.55),
    "led1": ((515, 360, 560, 680), cyan, 1.5, (0, 40, 70), (92, 205, 247), 6, 0.6),
    "led2": ((925, 375, 970, 790), cyan, 1.5, (0, 40, 70), (92, 205, 247), 6, 0.6),
}


def lamp_bands(mask, top, sy):
    """Row ranges (source px, absolute) that hold one lamp each; cut half-way between lamps."""
    px = mask.load()
    rows = [any(px[x, y] > 60 for x in range(mask.width)) for y in range(mask.height)]
    runs, start = [], None
    for y, on in enumerate(rows + [False]):
        if on and start is None:
            start = y
        elif not on and start is not None:
            runs.append((start, y))
            start = None
    cuts = [0] + [(a[1] + b[0]) // 2 for a, b in zip(runs, runs[1:])] + [mask.height]
    return [(top + cuts[i] / sy, top + cuts[i + 1] / sy) for i in range(len(runs))]


def main():
    im = Image.open(SRC).convert("RGB")
    OUT.mkdir(parents=True, exist_ok=True)
    sx, sy = im.width / W0, im.height / H0
    rects, bands = {}, {}
    for name, (box, mask_fn, gain, lift, halo_rgb, halo_r, halo_a) in PARTS.items():
        x0, y0, x1, y1 = (int(box[0] * sx), int(box[1] * sy), int(box[2] * sx), int(box[3] * sy))
        crop = im.crop((x0, y0, x1, y1))
        mask = Image.new("L", crop.size, 0)
        mp, cp = mask.load(), crop.load()
        for y in range(crop.height):
            for x in range(crop.width):
                mp[x, y] = int(255 * mask_fn(*cp[x, y]))
        mask = mask.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.8))
        r, g, b = crop.split()
        bright = Image.merge("RGB", tuple(c.point(lambda v, l=l: min(255, int(v * gain + l)))
                                          for c, l in zip((r, g, b), lift)))
        core = bright.convert("RGBA")
        core.putalpha(mask)
        halo = Image.new("RGBA", crop.size, halo_rgb + (0,))
        halo.putalpha(mask.filter(ImageFilter.GaussianBlur(halo_r)).point(lambda v: int(v * halo_a)))
        Image.alpha_composite(halo, core).save(OUT / f"{name}.png", optimize=True)
        rects[name] = (x0 / sx, y0 / sy, (x1 - x0) / sx, (y1 - y0) / sy)
        if name.startswith("led"):
            bands[name] = lamp_bands(mask, y0 / sy, sy)
    lines = ["// GENERATED by tools/make_portal_overlays.py - do not edit.",
             "import QtQuick", "",
             "// Light overlays cut from the photo (rects in source-art px, 1672x941).",
             "QtObject {"]
    for name, (x, y, w, h) in rects.items():
        lines.append(f'    readonly property var {name}: ({{ src: Qt.resolvedUrl("../../images/overlays/portals/{name}.png"), '
                     f'x: {x:.1f}, y: {y:.1f}, w: {w:.1f}, h: {h:.1f} }})')
    for name, bl in bands.items():
        lines.append(f'    readonly property var {name}Bands: [' + ", ".join(f"[{a:.1f}, {b:.1f}]" for a, b in bl) + "]")
    lines += ["}", ""]
    (PKG / "ui" / "scenes" / "PortalOverlays.qml").write_text("\n".join(lines), encoding="utf-8")
    print("ok:", ", ".join(rects))


if __name__ == "__main__":
    main()
